// Consistency guard: the JS mirror and the native helper must agree.
//
// The bridge allowlist and the chord denylist exist twice on purpose — the
// helper is authoritative, and the JS copy refuses bad input before a process is
// spawned. Duplication only stays honest if drift fails a test, so this file
// reads native-src/Program.cs as text and compares the two surfaces. It never
// compiles or runs the helper.

import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { helperVerbSurface } from "../app/hana-desktop-companion/lib/helper.js";
import { ACTION_RISK, TARGET_REQUIRED } from "../app/hana-desktop-companion/lib/gates.js";
import * as clipboardModule from "../app/hana-desktop-companion/lib/clipboard.js";
import { ALLOWED_KEYS, DENIED_CHORDS } from "../app/hana-desktop-companion/lib/shortcuts.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.resolve(here, "..", "native-src", "Program.cs");
const source = await fs.readFile(sourcePath, "utf8");

function quotedAll(text) {
  return [...text.matchAll(/"([^"\\]+)"/g)].map((match) => match[1]);
}

test("the native verb allowlist and the JS bridge expose the same surface", () => {
  const block = source.match(/AllowedFlags = new\(StringComparer\.OrdinalIgnoreCase\)\s*\{([\s\S]*?)\n    \};/);
  assert.ok(block, "AllowedFlags block not found in Program.cs");

  const native = {};
  for (const line of block[1].split("\n")) {
    const match = line.match(/\["([a-z-]+)"\]\s*=\s*(?:new\[\]\s*\{([^}]*)\}|Array\.Empty<string>\(\))/);
    if (!match) continue;
    native[match[1]] = match[2] ? quotedAll(match[2]) : [];
  }

  const bridge = helperVerbSurface();
  assert.deepEqual(Object.keys(native).sort(), Object.keys(bridge).sort());
  for (const verb of Object.keys(native)) {
    assert.deepEqual([...bridge[verb]].sort(), [...native[verb]].sort(), `flag drift for verb '${verb}'`);
  }
});

test("the native chord denylist matches the JS denylist exactly", () => {
  const block = source.match(/DeniedChords = new\(StringComparer\.Ordinal\)\s*\{([\s\S]*?)\n    \};/);
  assert.ok(block, "DeniedChords block not found in Program.cs");
  const native = quotedAll(block[1]).sort();
  assert.deepEqual(native, [...DENIED_CHORDS].sort());
});

test("the native key table matches the JS key allowlist", () => {
  const block = source.match(/private static Dictionary<string, ushort> BuildKeyTable\(\)\s*\{([\s\S]*?)\n    \}/);
  assert.ok(block, "BuildKeyTable block not found in Program.cs");
  const body = block[1];

  // Literal named keys, excluding the ones generated by the a-z / 0-9 / f1-f12 loops.
  // The interpolated "f{f}" template is part of the generated range, not a key name.
  const generated = (name) =>
    /^[a-z]$/.test(name) || /^[0-9]$/.test(name) || /^f([1-9]|1[0-2])$/.test(name) || name.includes("{");
  const nativeNamed = [...new Set(quotedAll(body))].filter((name) => !generated(name)).sort();
  const jsNamed = [...ALLOWED_KEYS].filter((name) => !generated(name)).sort();
  assert.deepEqual(nativeNamed, jsNamed);

  // The generated ranges must actually be generated on both sides.
  assert.match(body, /for \(var c = 'a'; c <= 'z'; c\+\+\)/);
  assert.match(body, /for \(var d = '0'; d <= '9'; d\+\+\)/);
  assert.match(body, /for \(var f = 1; f <= 12; f\+\+\)/);
});

test("every native verb is reachable through the bridge", () => {
  const bridge = helperVerbSurface();
  for (const verb of Object.keys(bridge)) {
    assert.doesNotThrow(() => helperVerbSurface()[verb], verb);
  }
  // And nothing in the bridge is missing from the helper's own switch.
  for (const verb of Object.keys(bridge)) {
    assert.match(source, new RegExp(`"${verb}" =>`), `verb '${verb}' has no native handler`);
  }
});

