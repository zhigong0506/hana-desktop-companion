// Removal guards and fail-closed shape checks.
//
// These are *source-shape* assertions, not runtime proof: they fail loudly if a
// later change reintroduces a removed capability or drops a fail-closed branch.
// Behavioural evidence lives in docs/VALIDATION.md and covers only what was
// actually observed there.
